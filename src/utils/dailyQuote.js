export function getDailyQuote(vkId){
const today=new Date().toISOString().slice(0,10);

let hash=0;

const str=`${vkId}_${today}`;

for(let i=0;i<str.length;i++){
hash=((hash<<5)-hash)+str.charCodeAt(i);
hash|=0;
}

const index=Math.abs(hash)%quotes.length;

return quotes[index];
}